import 'package:flutter_test/flutter_test.dart';
import 'package:open_timeline/models/entry.dart';
import 'package:open_timeline/models/entry_format.dart';

Entry sample({
  String id = '20261016-143205-k3f9',
  String author = 'a@gmail.com',
  DateTime? time,
  int offset = 120,
  Object? lat = 52.3702,
  Object? lon = 4.8952,
  Object? place = 'Scheveningen beach',
  String title = '',
  int? color,
  String text = 'Walked along the beach…\n\nSecond paragraph.',
  List<String> tags = const ['beach', 'family'],
  List<String> media = const [],
  bool deleted = false,
  bool conflict = false,
}) {
  return Entry(
    id: id,
    author: author,
    time: time ?? DateTime.utc(2026, 10, 16, 12, 32, 5),
    utcOffsetMinutes: offset,
    lat: lat as double?,
    lon: lon as double?,
    place: place as String?,
    title: title,
    color: color,
    text: text,
    tags: tags,
    media: media,
    updated: DateTime.utc(2026, 10, 16, 12, 40),
    deleted: deleted,
    conflict: conflict,
  );
}

void expectSame(Entry actual, Entry expected) {
  expect(actual.id, expected.id);
  expect(actual.author, expected.author);
  expect(actual.time, expected.time);
  expect(actual.time.isUtc, isTrue);
  expect(actual.utcOffsetMinutes, expected.utcOffsetMinutes);
  expect(actual.lat, expected.lat);
  expect(actual.lon, expected.lon);
  expect(actual.place, expected.place);
  expect(actual.title, expected.title);
  expect(actual.color, expected.color);
  expect(actual.text, expected.text);
  expect(actual.tags, expected.tags);
  expect(actual.media, expected.media);
  expect(actual.updated, expected.updated);
  expect(actual.deleted, expected.deleted);
  expect(actual.conflict, expected.conflict);
}

Entry roundTrip(Entry e) => entryFromMarkdown(entryToMarkdown(e));

void main() {
  group('writing', () {
    test('produces the documented format exactly', () {
      final e = sample(
        media: [
          '20261016-143205-k3f9_x7q2.jpg',
          '20261016-143205-k3f9_p0a1.mp4',
        ],
      );
      expect(entryToMarkdown(e), '''---
id: "20261016-143205-k3f9"
author: "a@gmail.com"
time: "2026-10-16T14:32:05+02:00"
location: [52.3702, 4.8952]
place: "Scheveningen beach"
tags: ["beach", "family"]
media: ["20261016-143205-k3f9_x7q2.jpg", "20261016-143205-k3f9_p0a1.mp4"]
updated: "2026-10-16T12:40:00.000Z"
deleted: false
conflict: false
---
Walked along the beach…

Second paragraph.

<!-- media: generated by Open Timeline, ignored when read -->
![](20261016-143205-k3f9_x7q2.jpg)
[video](20261016-143205-k3f9_p0a1.mp4)
''');
    });

    test('no location: location and place lines are omitted', () {
      final md = entryToMarkdown(sample(lat: null, lon: null, place: null));
      expect(md, isNot(contains('location:')));
      expect(md, isNot(contains('place:')));
    });

    test('empty media writes no media block', () {
      final md = entryToMarkdown(sample());
      expect(md, contains('media: []'));
      expect(md, isNot(contains('<!--')));
      expect(md.endsWith('Second paragraph.\n'), isTrue);
    });

    test('media block uses image / video / file links', () {
      final md = entryToMarkdown(
        sample(media: ['a.jpg', 'b.MOV', 'c.pdf', 'd.png']),
      );
      expect(
        md,
        contains('![](a.jpg)\n[video](b.MOV)\n[file](c.pdf)\n![](d.png)\n'),
      );
    });

    test('time is written in the post\'s own offset', () {
      String timeLine(Entry e) =>
          entryToMarkdown(e)
              .split('\n')
              .firstWhere((l) => l.startsWith('time:'));
      final instant = DateTime.utc(2026, 10, 16, 12, 32, 5);
      expect(
        timeLine(sample(time: instant, offset: 330)),
        'time: "2026-10-16T18:02:05+05:30"',
      );
      expect(
        timeLine(sample(time: instant, offset: -180)),
        'time: "2026-10-16T09:32:05-03:00"',
      );
      expect(
        timeLine(sample(time: instant, offset: 0)),
        'time: "2026-10-16T12:32:05Z"',
      );
      expect(
        timeLine(sample(time: instant, offset: -210)),
        'time: "2026-10-16T09:02:05-03:30"',
      );
    });

    test('empty body with media still gets the media block', () {
      final md = entryToMarkdown(sample(text: '', media: ['a.jpg']));
      expect(
        md,
        contains(
          '---\n<!-- media: generated by Open Timeline, ignored when read -->\n![](a.jpg)\n',
        ),
      );
    });
  });

  group('title', () {
    test('round trips with quotes and unicode', () {
      final e = sample(title: 'Dinner: "best" stroopwafel ☕');
      expect(entryFromMarkdown(entryToMarkdown(e)).title, e.title);
    });

    test('no title line is written when empty', () {
      expect(entryToMarkdown(sample()), isNot(contains('title:')));
      expect(entryFromMarkdown(entryToMarkdown(sample())).title, '');
    });
  });

  group('colour', () {
    test('is written as #RRGGBB and read back', () {
      final md = entryToMarkdown(sample(color: 0xFF9DBB9A));
      expect(md, contains('color: "#9DBB9A"'));
      expect(entryFromMarkdown(md).color, 0xFF9DBB9A);
    });

    test('is omitted when not chosen and ignored when invalid', () {
      expect(entryToMarkdown(sample()), isNot(contains('color:')));
      final md = entryToMarkdown(sample(color: 0xFF9DBB9A))
          .replaceFirst('#9DBB9A', 'pink');
      expect(entryFromMarkdown(md).color, isNull);
    });
  });

  group('round trip', () {
    test('every field', () {
      final e = sample(
        deleted: true,
        conflict: true,
        media: [
          '20261016-143205-k3f9_x7q2.jpg',
          '20261016-143205-k3f9_p0a1.mp4',
          'doc.pdf',
        ],
      );
      expectSame(roundTrip(e), e);
    });

    test('defaults (all booleans false) round-trip too', () {
      final e = sample();
      expectSame(roundTrip(e), e);
    });

    test('multi-paragraph text with --- lines and markdown', () {
      const text =
          '# Heading\n\n'
          'First paragraph with **bold** and _italic_.\n\n'
          '---\n\n'
          'After a rule.\n'
          '---\n'
          '- list item\n'
          '- another\n\n'
          '    indented code\n\n'
          '```dart\nfinal x = {"a": 1};\n```\n\n'
          '| a | b |\n|---|---|\n| 1 | 2 |\n\n'
          '> quote\n\n'
          '---';
      final e = sample(text: text, media: ['x.jpg']);
      expectSame(roundTrip(e), e);
      expectSame(roundTrip(sample(text: text)), sample(text: text));
    });

    test('text that itself looks like a header', () {
      const text = '---\nid: "evil"\ndeleted: true\n---\nreal text';
      final back = roundTrip(sample(text: text));
      expect(back.text, text);
      expect(back.id, '20261016-143205-k3f9');
      expect(back.deleted, isFalse);
    });

    test('unicode, emoji, colons, quotes and backslashes everywhere', () {
      final e = sample(
        author: 'zoë "the diarist" <z@example.com>',
        place: 'Café "Zum Löwen": 日本語 😀 #1 \\ back\\slash',
        text: 'Quote: "hi" and \'single\'\n# not a comment\nkey: value\n- [ ] todo\n🎉 Ünïcödé — ✓\n\\n literal',
        tags: [
          'a: b',
          '#hash',
          'quo"te',
          'emoji😀',
          'with space',
          'yes',
          'null',
          '123',
          'true',
        ],
        media: ['name with space (1).jpg', 'ü.png'],
      );
      final back = roundTrip(e);
      expectSame(back, e);
    });

    test('control characters in header strings survive', () {
      final e = sample(place: 'tab\there\nnewline\u0085next sep\u007f');
      expect(roundTrip(e).place, e.place);
    });

    test('offsets +05:30, -03:00 and Z', () {
      for (final offset in [330, -180, 0, -210, 840, -720]) {
        final e = sample(offset: offset);
        final back = roundTrip(e);
        expect(back.utcOffsetMinutes, offset, reason: 'offset $offset');
        expect(back.time, e.time);
        expect(back.wallTime, e.wallTime);
      }
    });

    test('sub-second precision of time and updated is kept', () {
      for (final t in [
        DateTime.utc(2026, 10, 16, 12, 32, 5, 123),
        DateTime.utc(2026, 10, 16, 12, 32, 5, 123, 456),
        DateTime.utc(2026, 10, 16, 12, 32, 5, 0, 7),
      ]) {
        final e = sample(time: t, offset: -180);
        expect(roundTrip(e).time, t);
      }
      final e = sample().copyWith(
        updated: DateTime.utc(2026, 1, 2, 3, 4, 5, 6, 7),
      );
      expect(roundTrip(e).updated, DateTime.utc(2026, 1, 2, 3, 4, 5, 6, 7));
    });

    test('time near midnight keeps date and offset consistent', () {
      final e = sample(time: DateTime.utc(2026, 12, 31, 23, 30), offset: 120);
      final md = entryToMarkdown(e);
      expect(md, contains('time: "2027-01-01T01:30:00+02:00"'));
      expectSame(roundTrip(e), e);
    });

    test('no location', () {
      final e = sample(lat: null, lon: null, place: null);
      final back = roundTrip(e);
      expect(back.lat, isNull);
      expect(back.lon, isNull);
      expect(back.place, isNull);
      expect(back.hasLocation, isFalse);
    });

    test('place without coordinates', () {
      final e = sample(lat: null, lon: null);
      final back = roundTrip(e);
      expect(back.place, 'Scheveningen beach');
      expect(back.hasLocation, isFalse);
    });

    test('negative and tiny coordinates', () {
      final e = sample(lat: -33.8688, lon: -0.000001);
      final back = roundTrip(e);
      expect(back.lat, -33.8688);
      expect(back.lon, -0.000001);
    });

    test('no tags, empty text', () {
      final e = sample(tags: [], text: '');
      expectSame(roundTrip(e), e);
      expectSame(
        roundTrip(sample(tags: [], text: '', media: ['a.jpg'])),
        sample(tags: [], text: '', media: ['a.jpg']),
      );
    });

    test('trailing whitespace of the body is trimmed, the rest is exact', () {
      final back = roundTrip(
        sample(text: '  indented first line\n\nlast line  \n\n  \n'),
      );
      expect(back.text, '  indented first line\n\nlast line');
    });

    test('Entry.create output round-trips', () {
      final e = Entry.create(
        author: 'me@example.com',
        now: DateTime(2026, 3, 4, 5, 6, 7, 8, 9),
      );
      final back = roundTrip(e);
      expect(back.id, e.id);
      expect(back.time, e.time);
      expect(back.utcOffsetMinutes, e.utcOffsetMinutes);
      expect(back.updated, e.updated);
    });
  });

  group('media block', () {
    test('is written and stripped on read; header list is the truth', () {
      final e = sample(media: ['k.jpg', 'v.mp4']);
      final md = entryToMarkdown(e);
      expect(md, contains('![](k.jpg)'));
      final back = entryFromMarkdown(md);
      expect(back.media, ['k.jpg', 'v.mp4']);
      expect(back.text, e.text);
      expect(back.text, isNot(contains('![](')));
      expect(back.text, isNot(contains('<!--')));
    });

    test('links in the body that were edited by hand are ignored', () {
      final md = entryToMarkdown(sample(media: ['k.jpg']))
          .replaceFirst('![](k.jpg)', '![](other.jpg)\n[video](more.mp4)');
      final back = entryFromMarkdown(md);
      expect(back.media, ['k.jpg']);
      expect(back.text, 'Walked along the beach…\n\nSecond paragraph.');
    });

    test('text links that precede the marker are kept as text', () {
      final e = sample(text: 'See ![](a.jpg) inline', media: ['a.jpg']);
      expect(roundTrip(e).text, 'See ![](a.jpg) inline');
    });
  });

  group('tolerant reading', () {
    test('missing optional keys get defaults', () {
      final e = entryFromMarkdown(
        '---\nid: "20261016-143205-k3f9"\ntime: "2026-10-16T14:32:05+02:00"\n---\nHi',
      );
      expect(e.author, '');
      expect(e.lat, isNull);
      expect(e.lon, isNull);
      expect(e.place, isNull);
      expect(e.tags, isEmpty);
      expect(e.media, isEmpty);
      expect(e.deleted, isFalse);
      expect(e.conflict, isFalse);
      expect(e.text, 'Hi');
      expect(e.time, DateTime.utc(2026, 10, 16, 12, 32, 5));
      expect(e.utcOffsetMinutes, 120);
      expect(e.updated, e.time);
    });

    test('unknown keys are ignored', () {
      final e = entryFromMarkdown('''---
id: "20261016-143205-k3f9"
author: "a@gmail.com"
time: "2026-10-16T14:32:05+02:00"
mood: happy
weather: {temp: 12, sky: "grey"}
aliases:
  - one
  - two
cssclass: wide
tags: ["x"]
---
body''');
      expect(e.tags, ['x']);
      expect(e.text, 'body');
      expect(e.author, 'a@gmail.com');
    });

    test('CRLF line endings', () {
      final lf = entryToMarkdown(sample(media: ['k.jpg']));
      final crlf = lf.replaceAll('\n', '\r\n');
      expectSame(entryFromMarkdown(crlf), entryFromMarkdown(lf));
      expect(
        entryFromMarkdown(crlf).text,
        'Walked along the beach…\n\nSecond paragraph.',
      );
      expect(entryFromMarkdown(crlf).text, isNot(contains('\r')));
    });

    test('byte order mark and leading blank lines before the header', () {
      final md = '﻿\n${entryToMarkdown(sample())}';
      expectSame(entryFromMarkdown(md), sample());
    });

    test('hand-written file by a human', () {
      final e = entryFromMarkdown('''---
id: 20261016-143205-k3f9
author: me@example.com
time: 2026-10-16T14:32:05+02:00
location: [52, 4]
place: Scheveningen beach
tags: [beach, family, 2026]
media: [a.jpg]
starred: true
---

Nice day. # not a comment in the body

Another line.
''');
      expect(e.id, '20261016-143205-k3f9');
      expect(e.author, 'me@example.com');
      expect(e.time, DateTime.utc(2026, 10, 16, 12, 32, 5));
      expect(e.utcOffsetMinutes, 120);
      expect(e.lat, 52.0);
      expect(e.lon, 4.0);
      expect(e.place, 'Scheveningen beach');
      expect(e.tags, ['beach', 'family', '2026']);
      expect(e.media, ['a.jpg']);
      expect(e.deleted, isFalse);
      expect(e.text, 'Nice day. # not a comment in the body\n\nAnother line.');
    });

    test('hand-written variants: comma tags, string coordinates, lat/lon keys, space-separated time', () {
      final a = entryFromMarkdown(
        '---\nid: 20261016-143205-k3f9\ntime: 2026-10-16 14:32\ntags: beach, family\nlocation: "52.5, 4.5"\n---\n',
      );
      expect(a.tags, ['beach', 'family']);
      expect(a.lat, 52.5);
      expect(a.lon, 4.5);
      expect(a.time, DateTime.utc(2026, 10, 16, 14, 32));
      expect(a.utcOffsetMinutes, 0);
      expect(a.text, '');

      final b = entryFromMarkdown(
        '---\nid: 20261016-143205-k3f9\ntime: 2026-10-16\nlat: 1\nlon: 2.5\ntags:\n  - x\n  - y\n---\nt',
      );
      expect(b.lat, 1.0);
      expect(b.lon, 2.5);
      expect(b.tags, ['x', 'y']);
      expect(b.time, DateTime.utc(2026, 10, 16));
    });

    test(
      'time without an offset is read as UTC, independent of the machine zone',
      () {
        final e = entryFromMarkdown(
          '---\nid: 20261016-143205-k3f9\ntime: "2026-10-16T14:32:05"\n---\n',
        );
        expect(e.time, DateTime.utc(2026, 10, 16, 14, 32, 5));
        expect(e.utcOffsetMinutes, 0);
      },
    );

    test('offset spellings: +0530, +05, lowercase z', () {
      DateTime t(String s) =>
          entryFromMarkdown('---\nid: 20261016-143205-k3f9\ntime: "$s"\n---\n')
              .time;
      int o(String s) =>
          entryFromMarkdown('---\nid: 20261016-143205-k3f9\ntime: "$s"\n---\n')
              .utcOffsetMinutes;
      expect(o('2026-10-16T14:32:05+0530'), 330);
      expect(o('2026-10-16T14:32:05+05'), 300);
      expect(o('2026-10-16T14:32:05z'), 0);
      expect(
        t('2026-10-16T14:32:05-03:00'),
        DateTime.utc(2026, 10, 16, 17, 32, 5),
      );
      expect(
        t('2026-10-16T14:32:05.250Z'),
        DateTime.utc(2026, 10, 16, 14, 32, 5, 250),
      );
    });

    test('missing time falls back to the creation time in the id', () {
      final e = entryFromMarkdown('---\nid: 20261016-143205-k3f9\n---\nx');
      expect(e.time, DateTime.utc(2026, 10, 16, 14, 32, 5));
    });

    test('missing id uses fallbackId', () {
      final e = entryFromMarkdown(
        '---\ntime: "2026-10-16T14:32:05Z"\n---\nx',
        fallbackId: '20261016-143205-k3f9',
      );
      expect(e.id, '20261016-143205-k3f9');
    });

    test('out-of-range coordinates are ignored, not fatal', () {
      final e = entryFromMarkdown(
        '---\nid: 20261016-143205-k3f9\ntime: 2026-10-16\nlocation: [123, 4]\n---\n',
      );
      expect(e.hasLocation, isFalse);
    });

    test('a body line "---" before the media marker is body text', () {
      final e = entryFromMarkdown(
        '---\nid: 20261016-143205-k3f9\ntime: 2026-10-16\n---\nabove\n---\nbelow',
      );
      expect(e.text, 'above\n---\nbelow');
    });
  });

  group('invalid files', () {
    void expectInvalid(String source, {String? fallbackId}) {
      expect(
        () => entryFromMarkdown(source, fallbackId: fallbackId),
        throwsA(isA<FormatException>()),
      );
    }

    test('no header at all', () {
      expectInvalid('Just some markdown\n\nwithout a header');
      expectInvalid('');
      expectInvalid('   \n\n');
    });

    test('header never closed', () {
      expectInvalid(
        '---\nid: "20261016-143205-k3f9"\ntime: "2026-10-16T14:32:05Z"\nbody',
      );
    });

    test('header is not a mapping', () {
      expectInvalid('---\n---\nbody');
      expectInvalid('---\njust a string\n---\nbody');
      expectInvalid('---\n- a\n- b\n---\nbody');
    });

    test('broken YAML', () {
      expectInvalid('---\nid: "unterminated\ntags: [a, b\n---\nbody');
      expectInvalid('---\n: : :\n  - [\n---\nbody');
    });

    test('missing or unsafe id', () {
      expectInvalid('---\ntime: 2026-10-16\n---\nbody');
      expectInvalid('---\nid: "../../etc/passwd"\ntime: 2026-10-16\n---\nbody');
      expectInvalid('---\nid: "abc"\ntime: 2026-10-16\n---\nbody');
      expectInvalid('---\nid: "2026/1016"\ntime: 2026-10-16\n---\nbody');
      expectInvalid(
        '---\ntime: 2026-10-16\n---\nbody',
        fallbackId: 'not-an-id',
      );
    });

    test('bad timestamps', () {
      for (final bad in [
        'yesterday',
        '2026-13-01T00:00:00Z',
        '2026-02-30T00:00:00Z',
        '2026-10-16T25:00:00Z',
        '2026-10-16T10:00:00+25:00',
        '2026-10-16T10:00:00+05:75',
      ]) {
        expectInvalid('---\nid: 20261016-143205-k3f9\ntime: "$bad"\n---\n');
      }
    });

    test('isValidEntryId', () {
      expect(isValidEntryId('20261016-143205-k3f9'), isTrue);
      expect(isValidEntryId('2026_x'), isTrue);
      expect(isValidEntryId(''), isFalse);
      expect(isValidEntryId('../x'), isFalse);
      expect(isValidEntryId('a.md'), isFalse);
    });
  });
}
